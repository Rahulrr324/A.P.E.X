#!/usr/bin/env python3
"""
Generate CONTROLLED aggregator fixture directories for M0 verification.

These are NOT measurements. Each fixture is derived from real records produced
by the production tools (profiler_cli / run_baseline) with a single, disclosed
edit so the aggregator's gate logic can be exercised on a known outcome:

  controlled-valid/       E1-B6 and E5-B6 given identical stats  -> all gates PASS
  controlled-invalid-g2/  E5 baseline removed                    -> G2/G4 FAIL
  controlled-invalid-g4/  E1 ram_measured=false                  -> G4 FAIL
  controlled-invalid-g7/  E5 median set 100% away from E1        -> G7 FAIL
  controlled-g7-endpoint-outlier/  three repeats 100/90/80 in one
                                  config group: adjacent diffs 10% and
                                  11.11% but endpoints 20% apart   -> G7 FAIL

Real, unmodified records are copied verbatim (PROFILE, TELEMETRY, the E2/B4/B5
skip records). Only the specific field named above is edited. Every generated
directory carries a README.txt stating exactly what was changed.
"""

import json
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "v14-valid")  # real records generated by the production tools

PROFILE = "P1-PROFILE-24-0.json"
TELEMETRY = "P1-TELEMETRY-24-1.json"
SKIPS = ["P1-E2-skip.json", "P1-B4-skip.json", "P1-B5-skip.json"]
E1_B6 = "P1-E1-B6-52043.json"
E5_B6 = "P1-E5-B6-7336.json"


def load(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return json.load(f)


def write(dirname, records, readme):
    d = os.path.join(HERE, dirname)
    if os.path.isdir(d):
        shutil.rmtree(d)
    os.makedirs(d)
    for name, rec in records.items():
        with open(os.path.join(d, name), "w", encoding="utf-8") as f:
            json.dump(rec, f, indent=2, sort_keys=True)
    with open(os.path.join(d, "README.txt"), "w", encoding="utf-8") as f:
        f.write(readme + "\n")
    print("wrote", dirname, "->", sorted(records))


def common_records():
    recs = {}
    for name in [PROFILE, TELEMETRY] + SKIPS:
        recs[name] = load(name)
    return recs


def mark_cpu_only(rec):
    """Declare confirmed CPU-only physical capability on a controlled fixture.

    v2.1: G4's capability classification keys on the OS device-inventory field
    hardware.gpu_present, NOT on cuda_available. These controlled fixtures are
    synthetic CPU-workload constructs, so they explicitly assert the CPU-only
    capability (gpu_present=false) instead of relying on a CUDA-less build flag.
    """
    rec.setdefault("hardware", {})["gpu_present"] = False
    return rec


def main():
    e1 = mark_cpu_only(load(E1_B6))
    e5 = mark_cpu_only(load(E5_B6))

    # --- controlled-valid: E5 carries the same stats as E1 ---
    e5_match = json.loads(json.dumps(e5))
    e5_match["statistics"] = json.loads(json.dumps(e1["statistics"]))
    valid = common_records()
    valid[E1_B6] = e1
    valid[E5_B6] = e5_match
    write(
        "controlled-valid",
        valid,
        "CONTROLLED TEST INPUT (not a measurement). Real records with one "
        "disclosed edit: the E5-B6 statistics block was replaced with the "
        "E1-B6 statistics block so the two independent runs of the same "
        "configuration agree, allowing G7 to pass. All gates are expected to PASS.",
    )

    # --- controlled-invalid-g2: E5 absent ---
    inv_g2 = common_records()
    inv_g2[E1_B6] = e1
    write(
        "controlled-invalid-g2",
        inv_g2,
        "CONTROLLED TEST INPUT. Same as controlled-valid but the E5 baseline "
        "record is omitted. G2 and G4 are expected to FAIL (E5 missing).",
    )

    # --- controlled-invalid-g4: E1 ram_measured=false ---
    e1_bad_ram = json.loads(json.dumps(e1))
    e1_bad_ram["peak_memory"]["ram_measured"] = False
    inv_g4 = common_records()
    inv_g4[E1_B6] = e1_bad_ram
    inv_g4[E5_B6] = e5_match
    write(
        "controlled-invalid-g4",
        inv_g4,
        "CONTROLLED TEST INPUT. Same as controlled-valid but E1-B6 has "
        "peak_memory.ram_measured=false. G4 is expected to FAIL.",
    )

    # --- controlled-invalid-g7: E5 median 100% away ---
    e5_off = json.loads(json.dumps(e5_match))
    m = e5_off["statistics"]["median"]
    e5_off["statistics"]["median"] = m * 2.0 if m else 1.0
    inv_g7 = common_records()
    inv_g7[E1_B6] = e1
    inv_g7[E5_B6] = e5_off
    write(
        "controlled-invalid-g7",
        inv_g7,
        "CONTROLLED TEST INPUT. Same as controlled-valid but the E5-B6 median "
        "is doubled (100% symmetric difference). G7 is expected to FAIL.",
    )

    # --- controlled-g7-endpoint-outlier ---
    # Three independent repeats of ONE configuration whose ADJACENT differences
    # are 10% and 11.11% (both <= 15%) but whose ENDPOINTS are 20% apart. This
    # isolates the v1.5 all-pairs requirement: an adjacent-only comparison would
    # wrongly PASS. E1/E5-B6 (matching) keep G2/G4 valid so only G7 is isolated.
    outlier = common_records()
    outlier[E1_B6] = e1
    outlier[E5_B6] = e5_match
    for tag, factor in (("r1", 1.0), ("r2", 0.9), ("r3", 0.8)):
        d = json.loads(json.dumps(e1))
        d["record_id"] = "P1-B2-" + tag
        d["experiment_id"] = "B2"
        d["kind"] = "benchmark"
        d["configuration"] = {"benchmark_id": "B2"}
        base = e1["statistics"]["median"]
        d["statistics"]["median"] = base * factor
        outlier["P1-B2-" + tag + ".json"] = d
    write(
        "controlled-g7-endpoint-outlier",
        outlier,
        "CONTROLLED TEST INPUT. E1/E5-B6 match (so G1-G6 pass); a B2 group has "
        "three independent repeats with medians at 100%, 90% and 80% of the base "
        "value: adjacent differences are 10% and 11.11% (within 15%) but the "
        "endpoints differ by 20%. G7 is expected to FAIL, isolating the all-pairs "
        "requirement.",
    )


if __name__ == "__main__":
    main()
